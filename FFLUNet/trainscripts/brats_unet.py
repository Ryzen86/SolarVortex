def zscore_normalize(image):
    image = image.copy()

    for c in range(image.shape[0]):

        modality = image[c]

        mask = modality > 0

        mean = modality[mask].mean()
        std = modality[mask].std()

        modality[mask] = (
            modality[mask] - mean
        ) / (std + 1e-8)

        image[c] = modality

    return image

