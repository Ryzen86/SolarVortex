import os
import glob
import cv2
import nibabel as nib
import numpy as np
import torch

from torch.utils.data import Dataset


class BraTS3DDataset(Dataset):

    def __init__(self, patients, target_size=(128, 128, 128)):
        self.patients = patients
        self.target_size = target_size

    def __len__(self):
        return len(self.patients)

    def zscore_normalize(self, volume):

        mask = volume > 0

        if np.sum(mask) == 0:
            return volume

        mean = volume[mask].mean()
        std = volume[mask].std()

        volume[mask] = (volume[mask] - mean) / (std + 1e-8)

        return volume

    def resize_volume(self, volume, target_size, is_mask=False):

        target_h, target_w, target_d = target_size

        h, w, d = volume.shape

        resized_slices = []

        interpolation = (
            cv2.INTER_NEAREST
            if is_mask
            else cv2.INTER_LINEAR
        )

        # resize each axial slice
        for z in range(d):

            slice_2d = volume[:, :, z]

            slice_resized = cv2.resize(
                slice_2d,
                (target_w, target_h),
                interpolation=interpolation
            )

            resized_slices.append(slice_resized)

        volume = np.stack(resized_slices, axis=-1)

        # resize depth dimension
        resized_depth = []

        for i in range(target_h):

            plane = volume[i, :, :]

            plane_resized = cv2.resize(
                plane,
                (target_d, target_w),
                interpolation=interpolation
            )

            resized_depth.append(plane_resized)

        volume = np.stack(resized_depth, axis=0)

        return volume

    def __getitem__(self, idx):

        patient_path = self.patients[idx]

        flair = nib.load(
            glob.glob(
                os.path.join(patient_path, "*_flair.nii")
            )[0]
        ).get_fdata()

        t1 = nib.load(
            glob.glob(
                os.path.join(patient_path, "*_t1.nii")
            )[0]
        ).get_fdata()

        t1ce = nib.load(
            glob.glob(
                os.path.join(patient_path, "*_t1ce.nii")
            )[0]
        ).get_fdata()

        t2 = nib.load(
            glob.glob(
                os.path.join(patient_path, "*_t2.nii")
            )[0]
        ).get_fdata()

        seg = nib.load(
            glob.glob(
                os.path.join(patient_path, "*_seg.nii")
            )[0]
        ).get_fdata()

        # --------------------------------
        # stack modalities
        # --------------------------------

        image = np.stack(
            [flair, t1, t1ce, t2],
            axis=0
        )

        # --------------------------------
        # crop brain bbox
        # --------------------------------

        brain_mask = np.any(image != 0, axis=0)

        x, y, z = np.where(brain_mask)

        xmin, xmax = x.min(), x.max()
        ymin, ymax = y.min(), y.max()
        zmin, zmax = z.min(), z.max()

        image = image[
            :,
            xmin:xmax+1,
            ymin:ymax+1,
            zmin:zmax+1
        ]

        seg = seg[
            xmin:xmax+1,
            ymin:ymax+1,
            zmin:zmax+1
        ]

        # --------------------------------
        # normalization
        # --------------------------------

        for c in range(4):
            image[c] = self.zscore_normalize(
                image[c]
            )

        # --------------------------------
        # label remap
        # --------------------------------

        seg[seg == 4] = 3

        # --------------------------------
        # resize modalities
        # --------------------------------

        resized_modalities = []

        for c in range(4):

            resized_modalities.append(
                self.resize_volume(
                    image[c],
                    self.target_size,
                    is_mask=False
                )
            )

        image = np.stack(
            resized_modalities,
            axis=0
        )

        seg = self.resize_volume(
            seg,
            self.target_size,
            is_mask=True
        )

        image = torch.tensor(
            image,
            dtype=torch.float32
        )

        seg = torch.tensor(
            seg,
            dtype=torch.long
        )

        return image, seg

